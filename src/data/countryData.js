function getRandomItems(array, count, excludeItem) {
  const filtered = array.filter((item) => item !== excludeItem);
  const shuffled = [...filtered].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

// Generate Flag Guesser questions
export function generateFlagQuestions(count = 10) {
  const shuffledCountries = [...COUNTRIES].sort(() => 0.5 - Math.random());
  const selected = shuffledCountries.slice(0, Math.min(count, shuffledCountries.length));

  return selected.map((country) => {
    const wrongCountries = getRandomItems(COUNTRIES, 3, country).map((c) => c.name);
    const options = [country.name, ...wrongCountries].sort(() => 0.5 - Math.random());

    return {
      type: "flag",
      question: "Which country does this flag belong to?",
      flagUrl: `https://flagcdn.com/w320/${country.code}.png`,
      correctAnswer: country.name,
      options,
      hint: `Continent: ${country.continent} | Capital: ${country.capital}`,
      funFact: country.funFact,
      countryData: country,
    };
  });
}

// Generate Capital Cities questions
export function generateCapitalQuestions(count = 10) {
  const shuffledCountries = [...COUNTRIES].sort(() => 0.5 - Math.random());
  const selected = shuffledCountries.slice(0, Math.min(count, shuffledCountries.length));

  return selected.map((country, idx) => {
    const isReverse = idx % 2 === 1; // alternate between "Capital of X" and "Which country has capital Y"

    if (isReverse) {
      const wrongCountries = getRandomItems(COUNTRIES, 3, country).map((c) => c.name);
      const options = [country.name, ...wrongCountries].sort(() => 0.5 - Math.random());
      return {
        type: "capital",
        question: `Which country's capital is ${country.capital}?`,
        correctAnswer: country.name,
        options,
        hint: `Located in ${country.continent}`,
        funFact: country.funFact,
        countryData: country,
      };
    } else {
      const wrongCapitals = getRandomItems(COUNTRIES, 3, country).map((c) => c.capital);
      const options = [country.capital, ...wrongCapitals].sort(() => 0.5 - Math.random());
      return {
        type: "capital",
        question: `What is the capital city of ${country.name}?`,
        correctAnswer: country.capital,
        options,
        hint: `Located in ${country.continent}`,
        funFact: country.funFact,
        countryData: country,
      };
    }
  });
}

// Generate Mixed Geography / Trivia questions
export function generateMixedQuestions(count = 10) {
  const flagSet = generateFlagQuestions(Math.ceil(count / 2));
  const capitalSet = generateCapitalQuestions(Math.floor(count / 2));
  const combined = [...flagSet, ...capitalSet].sort(() => 0.5 - Math.random());
  return combined.slice(0, count);
}

// Fetch from API with local fallback
export async function fetchQuestionsByMode(mode, count = 10, difficulty = "medium") {
  if (mode === "flags") {
    return generateFlagQuestions(count);
  }
  if (mode === "capitals") {
    return generateCapitalQuestions(count);
  }

  // mode === "trivia" or "timeAttack"
  try {
    const difficultyParam = difficulty ? `&difficulties=${difficulty}` : "";
    const response = await fetch(
      `https://the-trivia-api.com/v2/questions?limit=${count}&categories=geography${difficultyParam}`
    );
    if (!response.ok) throw new Error("API returned non-200");
    const data = await response.json();

    return data.map((item) => {
      const options = [item.correctAnswer, ...item.incorrectAnswers].sort(
        () => 0.5 - Math.random()
      );
      return {
        type: "trivia",
        question: item.question.text,
        correctAnswer: item.correctAnswer,
        options,
        hint: `Category: Geography (${item.difficulty || "standard"})`,
        funFact: `Fact: ${item.tags?.join(", ") || "A classic world geography challenge"}`,
      };
    });
  } catch (error) {
    console.warn("Online trivia fetch failed, using rich local geographic database:", error);
    return generateMixedQuestions(count);
  }
}
