function getRandomOptions(array, count, excludeItem) {
  const filtered = array.filter((item) => item !== excludeItem);
  const shuffled = [...filtered].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

// Filter dataset by continent
export function getFilteredCountries(continentFilter = "All") {
  if (!continentFilter || continentFilter === "All") {
    return COUNTRIES;
  }
  return COUNTRIES.filter((c) => c.continent.toLowerCase() === continentFilter.toLowerCase());
}

// Generate Flag Guesser questions
export function generateFlagQuestions(count = 10, continent = "All") {
  const pool = getFilteredCountries(continent);
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  const selected = shuffled.slice(0, Math.min(count, shuffled.length));

  return selected.map((country) => {
    const wrongOptions = getRandomOptions(pool, 3, country).map((c) => c.name);
    const options = [country.name, ...wrongOptions].sort(() => 0.5 - Math.random());

    return {
      type: "flag",
      question: "Which country does this flag belong to?",
      flagUrl: `https://flagcdn.com/w320/${country.code}.png`,
      correctAnswer: country.name,
      options,
      hint: `Continent: ${country.continent} | Capital: ${country.capital}`,
      funFact: country.funFact,
      countryData: country,
    };
  });
}

// Generate Capital Cities questions
export function generateCapitalQuestions(count = 10, continent = "All") {
  const pool = getFilteredCountries(continent);
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  const selected = shuffled.slice(0, Math.min(count, shuffled.length));

  return selected.map((country, idx) => {
    const isReverse = idx % 2 === 1;

    if (isReverse) {
      const wrongCountries = getRandomOptions(pool, 3, country).map((c) => c.name);
      const options = [country.name, ...wrongCountries].sort(() => 0.5 - Math.random());
      return {
        type: "capital",
        question: `Which country's capital is ${country.capital}?`,
        correctAnswer: country.name,
        options,
        hint: `Located in ${country.continent} | Currency: ${country.currency}`,
        funFact: country.funFact,
        countryData: country,
      };
    } else {
      const wrongCapitals = getRandomOptions(pool, 3, country).map((c) => c.capital);
      const options = [country.capital, ...wrongCapitals].sort(() => 0.5 - Math.random());
      return {
        type: "capital",
        question: `What is the capital city of ${country.name}?`,
        correctAnswer: country.capital,
        options,
        hint: `Located in ${country.continent} | Population: ${country.population}`,
        funFact: country.funFact,
        countryData: country,
      };
    }
  });
}

// Generate Landmark & Geography questions
